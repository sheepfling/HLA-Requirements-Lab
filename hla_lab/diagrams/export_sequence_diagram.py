"""Export validated sequence-diagram records to Mermaid and standalone TikZ."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from hla_lab.core.semantic_model import SequenceDiagram, SequenceDiagramFile
from hla_lab.core.text import format_number, mermaid_text, safe_identifier, tex_escape


def render_mermaid(diagram: SequenceDiagram) -> str:
    """Render a sequence diagram using Mermaid's stable sequence syntax."""
    aliases = {
        item.id: safe_identifier(item.id, prefix="participant") for item in diagram.participants
    }
    lines = [
        f"%% Generated from semantic sequence diagram {diagram.id}; edit JSON instead.",
        "sequenceDiagram",
    ]
    for participant in diagram.participants:
        lines.append(
            f'  participant {aliases[participant.id]} as "{mermaid_text(participant.label)}"'
        )
    for message in sorted(diagram.messages, key=lambda item: item.order):
        arrow = "-->>" if message.kind == "response" else "->>"
        lines.append(
            f"  {aliases[message.source_participant]}{arrow}"
            f"{aliases[message.target_participant]}: {mermaid_text(message.label)}"
        )
    return "\n".join(lines) + "\n"


def render_tikz(diagram: SequenceDiagram) -> str:
    """Render a sequence diagram as deterministic, dependency-light TikZ."""
    participant_x = {item.id: index * 4.5 for index, item in enumerate(diagram.participants)}
    row_gap = 1.1
    lines = [
        "% Generated by hla_lab/diagrams/export_sequence_diagram.py; edit semantic JSON instead.",
        "\\begin{tikzpicture}[x=1cm,y=1cm,>=stealth,",
        "  seq-participant/.style={draw,rounded corners,minimum width=2.7cm,"
        "minimum height=0.65cm,font=\\small,align=center},",
        "  seq-lifeline/.style={dashed,line width=0.45pt},",
        "  seq-message/.style={->,line width=0.55pt},",
        "  seq-label/.style={font=\\scriptsize,fill=white,inner sep=1pt,"
        "text width=3.4cm,align=center},",
        "]",
    ]
    for participant in diagram.participants:
        x = participant_x[participant.id]
        lines.append(
            f"\\node[seq-participant] ({safe_identifier(participant.id, prefix='seq')}) at "
            f"({format_number(x)},0) {{ {tex_escape(participant.label)} }};"
        )
        lines.append(
            f"\\draw[seq-lifeline] ({format_number(x)},-0.38) -- "
            f"({format_number(x)},-{format_number((len(diagram.messages) + 1) * row_gap)});"
        )
    for message in sorted(diagram.messages, key=lambda item: item.order):
        source_x = participant_x[message.source_participant]
        target_x = participant_x[message.target_participant]
        y = -message.order * row_gap
        if source_x == target_x:
            lines.append(
                f"\\draw[seq-message] ({format_number(source_x)},{format_number(y)}) "
                "to[loop right] "
                "node[seq-label,pos=.5,xshift=1.6cm,yshift=.22cm] "
                f"{{ {tex_escape(message.label)} }}"
                f" ({format_number(target_x)},{format_number(y - 0.55)});"
            )
        else:
            lines.append(
                f"\\draw[seq-message] ({format_number(source_x)},{format_number(y)}) -- "
                "node[seq-label,pos=.5,yshift=.22cm] "
                f"{{ {tex_escape(message.label)} }} ({format_number(target_x)},{format_number(y)});"
            )
    lines.extend(["\\end{tikzpicture}", ""])
    return "\n".join(lines)


def load_diagrams(path: Path) -> tuple[SequenceDiagram, ...]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    return SequenceDiagramFile.model_validate(payload).sequence_diagrams


def export(
    model: Path,
    output: Path,
    *,
    diagram_ids: tuple[str, ...] = (),
    formats: tuple[str, ...] = ("tikz", "mermaid"),
) -> tuple[Path, ...]:
    diagrams = load_diagrams(model)
    selected = (
        tuple(item for item in diagrams if item.id in diagram_ids) if diagram_ids else diagrams
    )
    missing = set(diagram_ids) - {item.id for item in selected}
    if missing:
        raise ValueError(f"unknown sequence diagram IDs: {sorted(missing)}")
    output.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []
    for diagram in selected:
        safe = safe_identifier(diagram.id, prefix="")
        if "tikz" in formats:
            path = output / f"{safe}.tex"
            path.write_text(render_tikz(diagram), encoding="utf-8")
            paths.append(path)
        if "mermaid" in formats:
            path = output / f"{safe}.mmd"
            path.write_text(render_mermaid(diagram), encoding="utf-8")
            paths.append(path)
    return tuple(paths)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path, help="Canonical sequence-diagram JSON")
    parser.add_argument("--output", type=Path, required=True, help="Ignored export directory")
    parser.add_argument("--diagram", action="append", default=[])
    parser.add_argument("--format", choices=("tikz", "mermaid", "both"), default="both")
    args = parser.parse_args()
    formats = ("tikz", "mermaid") if args.format == "both" else (args.format,)
    for path in export(
        args.model,
        args.output,
        diagram_ids=tuple(args.diagram),
        formats=formats,
    ):
        print(path)


if __name__ == "__main__":
    main()
